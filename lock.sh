#!/bin/bash
# Regenerate tl-lock.txt: the TeX Live packages (and their versions) that the
# resume and cover letter actually load. Run after a successful build.
#
# tlmgr cannot install specific versions, so this file is a record, not an
# installer input. Diff it against a fresh one on a new machine to see which
# packages changed if the layout ever shifts.

set -euo pipefail
cd "$(dirname "$0")"

FLS_FILES=(resume.fls cover-letter.fls)
for f in "${FLS_FILES[@]}"; do
  if [ ! -r "$f" ]; then
    echo "$f not found. Build first: latexmk -xelatex ${f%.fls}.tex" >&2
    exit 1
  fi
done

ROOT=$(kpsewhich -var-value=SELFAUTOPARENT)
TLPDB="$ROOT/tlpkg/texlive.tlpdb"

{
  echo "# Generated by lock.sh on $(date +%Y-%m-%d). Do not edit by hand."
  echo "# $(tlmgr --version | sed -n 1p)"
  echo "# $(tlmgr --version | grep -o 'TeX Live .*version [0-9]*')"
  echo "# $(xelatex --version | sed -n 1p)"
  echo "# LaTeX kernel: $(grep -m1 -o 'LaTeX2e <[^>]*>' resume.log)"
  echo "#"
  echo "# package,revision,version"
  # Files read from the TeX Live tree during the build...
  grep -h '^INPUT ' "${FLS_FILES[@]}" \
    | sed -n "s|^INPUT $ROOT/||p" | sort -u \
  | awk -v tlpdb="$TLPDB" '
      # ...mapped to the TeX Live package that owns each file.
      BEGIN {
        while ((getline line < tlpdb) > 0) {
          if (line ~ /^name /)                   name = substr(line, 6)
          else if (line ~ /^revision /)          rev[name] = substr(line, 10)
          else if (line ~ /^catalogue-version /) ver[name] = substr(line, 19)
          else if (line ~ /^ /) { split(substr(line, 2), f, " "); owner[f[1]] = name }
        }
      }
      ($0 in owner) { used[owner[$0]] = 1 }
      END { for (p in used) printf "%s,%s,%s\n", p, rev[p], ver[p] }
    ' | sort
} > tl-lock.txt

echo "Wrote tl-lock.txt ($(grep -vc '^#' tl-lock.txt) packages)"
